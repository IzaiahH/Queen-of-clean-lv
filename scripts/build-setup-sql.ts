/**
 * Writes supabase/setup.sql: every migration plus the base seed as one file that can be pasted into
 * the Supabase SQL editor (no local tools needed). Regenerate after changing migrations or seed data:
 *   npx tsx scripts/build-setup-sql.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_RULES } from "../src/lib/pricing/rules";
import { ADDONS, AREAS, SERVICES } from "./seed";

const lit = (v: string) => `'${v.replace(/'/g, "''")}'`;
const arr = (a: readonly string[]) => (a.length ? `array[${a.map(lit).join(", ")}]::text[]` : `'{}'::text[]`);

const dir = join(process.cwd(), "supabase/migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const out: string[] = [
  "-- Queen of Clean LV: complete database setup for a NEW, EMPTY Supabase project.",
  "-- Paste this whole file into Supabase → SQL Editor → New query, then click Run.",
  "-- Generated by scripts/build-setup-sql.ts. Contains no customer data.",
  "",
  "begin;",
  "create table if not exists schema_migrations (name text primary key, applied_at timestamptz not null default now());",
  "alter table schema_migrations enable row level security;",
];
for (const f of files) {
  out.push("", `-- ── migration ${f} ──`, readFileSync(join(dir, f), "utf8").trim(), `insert into schema_migrations (name) values (${lit(f)});`);
}
out.push("", "-- ── base catalog, service areas and first prices ──");
SERVICES.forEach((s, i) =>
  out.push(`insert into services (slug, name, short_description, description, includes, excludes, kind, allowed_frequencies, requires_review, active, sort) values (${lit(s.slug)}, ${lit(s.name)}, ${lit(s.short)}, ${lit(s.description)}, ${arr(s.includes)}, ${arr(s.excludes)}, ${lit(s.kind)}, ${arr(s.freqs)}, ${s.review}, ${s.active}, ${i}) on conflict (slug) do nothing;`),
);
ADDONS.forEach(([slug, name, description], i) => out.push(`insert into addons (slug, name, description, sort) values (${lit(slug)}, ${lit(name)}, ${lit(description)}, ${i}) on conflict (slug) do nothing;`));
AREAS.forEach((a, i) => out.push(`insert into service_areas (name, zip_codes, sort) values (${lit(a.name)}, ${arr(a.zips)}, ${i}) on conflict do nothing;`));
out.push(
  `insert into pricing_versions (version, status, rules, notes, published_at) select 1, 'published', ${lit(JSON.stringify(DEFAULT_RULES))}::jsonb, 'Initial draft prices — review in Admin → Pricing & Services', now() where not exists (select 1 from pricing_versions);`,
  "",
  "commit;",
  "",
);
writeFileSync(join(process.cwd(), "supabase/setup.sql"), out.join("\n"));
console.log(`Wrote supabase/setup.sql (${files.length} migration(s) + base seed).`);
